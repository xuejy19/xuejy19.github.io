'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:4000';
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH || (process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : undefined)});
  try {
    const dir = path.resolve(__dirname, '../.cache/previews'); fs.mkdirSync(dir,{recursive:true});
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[]; page.on('pageerror', error=>errors.push(error.message));
    await page.route('**/*', route=> new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
    await page.goto(base,{waitUntil:'networkidle'});
    assert.ok((await page.title()).includes('薛建业'));
    assert.equal(await page.locator('#academic-home h1').count(),1);
    assert.equal(await page.locator('#notes .note').count(),3);
    assert.ok(await page.locator('.portrait img').evaluate(img=>img.complete && img.naturalWidth>0));
    await page.screenshot({path:path.join(dir,'home-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Academic homepage mobile overflow');
    await page.screenshot({path:path.join(dir,'home-mobile.png'),fullPage:true});
    await page.getByRole('navigation').getByRole('link',{name:'学术兴趣'}).click();
    await page.waitForURL('**/#interests');
    // Follow the real blog entry, then preserve the Matery interaction checks.
    let releaseIndex; const gate=new Promise(resolve=>{releaseIndex=resolve;});
    await page.route('**/search.xml', async route=>{await gate;await route.continue();});
    await page.getByRole('navigation').getByRole('link',{name:'博客'}).click();
    await page.waitForURL('**/blog/');
    await page.setViewportSize({width:1440,height:1000});
    await page.waitForFunction(()=>window.M && window.M.Modal && window.M.Modal.getInstance(document.querySelector('#searchModal')));
    assert.ok((await page.title()).includes('风之声'));
    assert.equal(await page.locator('#articles .article').count(),12);
    await page.screenshot({path:path.join(dir,'blog-desktop.png')});
    await page.locator('a[href="#searchModal"]:visible').first().click();
    await page.locator('#searchInput').fill('docker'); releaseIndex();
    await page.locator('#searchResult a').first().waitFor();
    assert.ok((await page.locator('#searchResult').innerText()).toLowerCase().includes('docker'));
    await page.locator('#searchInput').fill('[');
    await page.waitForFunction(()=>!document.querySelector('#searchResult').textContent.includes('正在搜索'));
    await page.goto(base+'/2020/08/12/svm/',{waitUntil:'networkidle'});
    assert.ok(await page.locator('#articleContent .katex').count()>10);
    await page.waitForFunction(()=>document.querySelectorAll('#toc-content a').length>0);
    const first=page.locator('#toc-content a').first();const target=await first.getAttribute('href');await first.click();
    await page.waitForFunction(hash=>decodeURIComponent(location.hash)===decodeURIComponent(hash),target);
    await page.screenshot({path:path.join(dir,'article-desktop.png')});
    await page.goto(base+'/2020/01/12/blog/',{waitUntil:'networkidle'});
    assert.ok(await page.locator('#hbePass').isVisible());
    await page.setViewportSize({width:390,height:844});
    await page.goto(base+'/blog/',{waitUntil:'networkidle'});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Homepage mobile overflow');
    await page.screenshot({path:path.join(dir,'blog-mobile.png')});
    await page.locator('.sidenav-trigger').click();
    await page.locator('#mobile-nav a[href="/about"]').click();
    await page.waitForURL('**/about/');
    assert.ok((await page.locator('#aboutme').innerText()).includes('思考猫'));
    await page.goto(base+'/2020/08/12/svm/',{waitUntil:'networkidle'});
    await page.locator('#articleContent .katex-display').first().scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Article mobile overflow');
    await page.screenshot({path:path.join(dir,'article-mobile.png')});
    await page.goto(base+'/2022/11/03/docker-xue-xi/',{waitUntil:'networkidle'});
    assert.ok(await page.locator('pre code').count()>5);
    await page.goto(base+'/page/2/',{waitUntil:'networkidle'});
    await page.waitForURL('**/blog/page/2/');
    assert.equal(await page.locator('#articles .article').count(),12);
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('Academic homepage and Matery browser checks passed: responsive layout, blog entry, pagination, search, math, TOC, encrypted UI, mobile navigation and code.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
